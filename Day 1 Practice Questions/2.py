# Q2
# Take two numbers and print:
# addition
# subtraction
# multiplication
# division


num1 = int(input("Enter first number:"))
num2 = int(input("Enter second number:"))

print(f"{num1} + {num2} = ", num1 + num2)
print(f"{num1} - {num2} = ", num1 - num2)
print(f"{num1} x {num2} = ", num1 * num2)
print(f"{num1} / {num2} = ", num1 / num2)